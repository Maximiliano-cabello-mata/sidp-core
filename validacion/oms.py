LMS = {'H': _H, 'M': _M}
DESDE, HASTA = 60, 60 + len(_H) - 1
CLASES = ('Delgadez severa', 'Delgadez', 'Peso normal', 'Sobrepeso', 'Obesidad')


def meses_cumplidos(nacimiento, dia):
    meses = (dia.year - nacimiento.year) * 12 + dia.month - nacimiento.month
    return meses - (dia.day < nacimiento.day)


def imc(peso, talla):
    """kg / m²; la talla puede venir en metros o en centímetros. None si no cuadra con un niño."""
    try:
        peso, talla = float(str(peso).replace(',', '.')), float(str(talla).replace(',', '.'))
    except (TypeError, ValueError):
        return None
    talla = talla / 100 if talla > 3 else talla
    if not (10 <= peso <= 120 and 0.9 <= talla <= 1.9):
        return None
    return round(peso / talla ** 2, 1)


def puntuacion_z(valor_imc, sexo, meses):
    """Puntuación z del IMC para la edad (con el ajuste de la OMS arriba de 3 y abajo de -3). None fuera de la tabla."""
    if valor_imc is None or sexo not in LMS or not DESDE <= meses <= HASTA:
        return None
    l, m, s = LMS[sexo][meses - DESDE]
    z = ((valor_imc / m) ** l - 1) / (l * s)
    if abs(z) <= 3:
        return round(z, 2) + 0.0  # Sin "-0.0".
    corte = (lambda d: m * (1 + l * s * d) ** (1 / l))
    if z > 3:
        return round(3 + (valor_imc - corte(3)) / (corte(3) - corte(2)), 2)
    return round(-3 - (corte(-3) - valor_imc) / (corte(-2) - corte(-3)), 2)


def clase(z):
    if z is None:
        return None
    if z < -3:
        return CLASES[0]
    if z < -2:
        return CLASES[1]
    if z <= 1:
        return CLASES[2]
    if z <= 2:
        return CLASES[3]
    return CLASES[4]


def estado_nutricional(peso, talla, sexo, nacimiento, dia=None):
    """{'imc', 'z', 'clase'} de un alumno, o None si falta el peso, la talla o la fecha de nacimiento."""
    if isinstance(nacimiento, str):
        try:
            nacimiento = datetime.date.fromisoformat(nacimiento[:10])
        except ValueError:
            return None
    valor = imc(peso, talla)
    if valor is None or not nacimiento:
        return None
    z = puntuacion_z(valor, sexo, meses_cumplidos(nacimiento, dia or datetime.date.today()))
    return {'imc': valor, 'z': z, 'clase': clase(z)}
